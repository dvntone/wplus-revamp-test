package com.wscanplus.android.core

import android.net.wifi.ScanResult
import android.util.Log
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import org.json.JSONArray
import org.json.JSONObject
import java.io.OutputStreamWriter
import java.net.HttpURLConnection
import java.net.URL

/**
 * CompanionClient – connects the Android app to the wscan+ Windows desktop
 * companion relay server ([CompanionRelayServer]).
 *
 * Typical usage:
 *  1. User enters the desktop host (e.g. "192.168.1.100:9000") in Settings.
 *  2. Each scan cycle, [pushScanResults] forwards the AP list to the desktop
 *     for correlation with Npcap-level packet captures.
 *  3. [fetchAlerts] pulls back any high-confidence alerts the desktop raised.
 *
 * Protocol: JSON over HTTP (same LAN, no TLS required for local use).
 */
class CompanionClient(private val host: String) {

    private val baseUrl = if (host.startsWith("http")) host else "http://$host"

    // ── Public API ────────────────────────────────────────────────────────────

    /**
     * Test connectivity to the desktop relay server.
     * @return true if the server responds with status "ok".
     */
    suspend fun ping(): Boolean = withContext(Dispatchers.IO) {
        return@withContext try {
            val json = get("/ping") ?: return@withContext false
            json.optString("status") == "ok"
        } catch (e: kotlinx.coroutines.CancellationException) {
            throw e
        } catch (e: Exception) {
            Log.w(TAG, "ping failed: ${e.message}")
            false
        }
    }

    /**
     * Push the current list of visible access points to the desktop app
     * for additional heuristic analysis.
     *
     * @param scanResults Android Wi-Fi scan results to forward.
     * @return List of threat descriptions returned by the desktop, or empty on failure.
     */
    suspend fun pushScanResults(scanResults: List<ScanResult>): List<String> =
        withContext(Dispatchers.IO) {
            return@withContext try {
                val body = JSONArray().apply {
                    for (ap in scanResults) {
                        put(JSONObject().apply {
                            put("bssid", ap.BSSID ?: "")
                            put("ssid", ap.SSID ?: "")
                            put("rssi", ap.level)
                            put("capabilities", ap.capabilities ?: "")
                        })
                    }
                }.toString()

                val response = post("/scan", body) ?: return@withContext emptyList()
                val threats = response.optJSONArray("threats") ?: return@withContext emptyList()
                List(threats.length()) { i ->
                    threats.getJSONObject(i).optString("description")
                }.filter { it.isNotBlank() }
            } catch (e: kotlinx.coroutines.CancellationException) {
                throw e
            } catch (e: Exception) {
                Log.e(TAG, "pushScanResults failed", e)
                emptyList()
            }
        }

    /**
     * Fetch the latest threat alerts generated by the desktop app.
     *
     * @return List of alert descriptions, or empty on failure.
     */
    suspend fun fetchAlerts(): List<String> = withContext(Dispatchers.IO) {
        return@withContext try {
            val json = get("/alerts") ?: return@withContext emptyList()
            val alerts = json.optJSONArray("alerts") ?: return@withContext emptyList()
            List(alerts.length()) { i ->
                alerts.getJSONObject(i).optString("description")
            }.filter { it.isNotBlank() }
        } catch (e: kotlinx.coroutines.CancellationException) {
            throw e
        } catch (e: Exception) {
            Log.e(TAG, "fetchAlerts failed", e)
            emptyList()
        }
    }

    // ── HTTP helpers ──────────────────────────────────────────────────────────

    private fun get(path: String): JSONObject? {
        val conn = URL("$baseUrl$path").openConnection() as HttpURLConnection
        return try {
            conn.requestMethod = "GET"
            conn.connectTimeout = 5_000
            conn.readTimeout = 10_000
            if (conn.responseCode != 200) return null
            JSONObject(conn.inputStream.bufferedReader().readText())
        } finally {
            conn.disconnect()
        }
    }

    private fun post(path: String, body: String): JSONObject? {
        val conn = URL("$baseUrl$path").openConnection() as HttpURLConnection
        return try {
            conn.requestMethod = "POST"
            conn.doOutput = true
            conn.connectTimeout = 5_000
            conn.readTimeout = 15_000
            conn.setRequestProperty("Content-Type", "application/json")
            OutputStreamWriter(conn.outputStream, Charsets.UTF_8).use { it.write(body) }
            if (conn.responseCode != 200) return null
            JSONObject(conn.inputStream.bufferedReader().readText())
        } finally {
            conn.disconnect()
        }
    }

    companion object {
        private const val TAG = "CompanionClient"
    }
}
